#!/usr/bin/env bash
set -euo pipefail

: "${POSTGRES_DB:?POSTGRES_DB is required}"
: "${POSTGRES_USER:?POSTGRES_USER is required}"
: "${GRUNDET_MIGRATOR_USER:?GRUNDET_MIGRATOR_USER is required}"
: "${GRUNDET_MIGRATOR_PASSWORD:?GRUNDET_MIGRATOR_PASSWORD is required}"
: "${GRUNDET_API_USER:?GRUNDET_API_USER is required}"
: "${GRUNDET_API_PASSWORD:?GRUNDET_API_PASSWORD is required}"

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "${POSTGRES_DB}" <<-EOSQL
DO \$\$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${GRUNDET_MIGRATOR_USER}') THEN
        EXECUTE format(
            'CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS',
            '${GRUNDET_MIGRATOR_USER}',
            '${GRUNDET_MIGRATOR_PASSWORD}');
    ELSE
        EXECUTE format('ALTER ROLE %I WITH NOBYPASSRLS NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION',
            '${GRUNDET_MIGRATOR_USER}');
        EXECUTE format('ALTER ROLE %I WITH PASSWORD %L',
            '${GRUNDET_MIGRATOR_USER}',
            '${GRUNDET_MIGRATOR_PASSWORD}');
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${GRUNDET_API_USER}') THEN
        EXECUTE format(
            'CREATE ROLE %I LOGIN PASSWORD %L NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS',
            '${GRUNDET_API_USER}',
            '${GRUNDET_API_PASSWORD}');
    ELSE
        EXECUTE format('ALTER ROLE %I WITH NOBYPASSRLS NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION',
            '${GRUNDET_API_USER}');
        EXECUTE format('ALTER ROLE %I WITH PASSWORD %L',
            '${GRUNDET_API_USER}',
            '${GRUNDET_API_PASSWORD}');
    END IF;
END
\$\$;

ALTER DATABASE "${POSTGRES_DB}" OWNER TO "${GRUNDET_MIGRATOR_USER}";
ALTER SCHEMA public OWNER TO "${GRUNDET_MIGRATOR_USER}";

REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CREATE ON SCHEMA public TO "${GRUNDET_MIGRATOR_USER}";
GRANT USAGE ON SCHEMA public TO "${GRUNDET_API_USER}";

GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${GRUNDET_MIGRATOR_USER}";
GRANT CONNECT ON DATABASE "${POSTGRES_DB}" TO "${GRUNDET_API_USER}";

ALTER DEFAULT PRIVILEGES FOR ROLE "${GRUNDET_MIGRATOR_USER}" IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "${GRUNDET_API_USER}";

ALTER DEFAULT PRIVILEGES FOR ROLE "${GRUNDET_MIGRATOR_USER}" IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO "${GRUNDET_API_USER}";
EOSQL
